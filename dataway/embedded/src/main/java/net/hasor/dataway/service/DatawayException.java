package net.hasor.dataway.service;

public class DatawayException extends RuntimeException {
    private final int status;

    public DatawayException(int status, String message) {
        super(message);
        this.status = status;
    }

    public DatawayException(int status, String message, Throwable cause) {
        super(message, cause);
        this.status = status;
    }

    public int status() {
        return status;
    }
}
